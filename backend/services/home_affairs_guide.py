_groq_client: "Groq | None" = None
_groq_client_checked = False


def _get_groq_client() -> "Groq | None":
    global _groq_client, _groq_client_checked
    if _groq_client_checked:
        return _groq_client
    _groq_client_checked = True
    if Groq is None:
        logger.info("groq package not installed; home_affairs_guide will use the deterministic path only.")
        return None
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        logger.info("GROQ_API_KEY not set; home_affairs_guide will use the deterministic path only.")
        return None
    _groq_client = Groq(api_key=api_key)
    return _groq_client


def reset_groq_client() -> None:
    """Test hook: clears the cached client so a test can toggle GROQ_API_KEY
    and observe the effect."""
    global _groq_client, _groq_client_checked
    _groq_client = None
    _groq_client_checked = False


def _call_groq_json(system_prompt: str, user_prompt: str) -> dict[str, Any] | None:
    """Deterministic-mode, JSON-structured Groq call. Returns the parsed
    object, or None on any failure (missing client, API error, timeout,
    malformed JSON) — callers must treat None as "fall back"."""
    client = _get_groq_client()
    if client is None:
        return None
    try:
        completion = client.chat.completions.create(
            model=_GROQ_MODEL,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0,
            response_format={"type": "json_object"},
            timeout=_GROQ_TIMEOUT_SECONDS,
        )
        content = completion.choices[0].message.content
        return json.loads(content)
    except Exception:
        logger.warning("Groq JSON classification call failed; falling back to deterministic logic", exc_info=True)
        return None


def _call_groq_text(system_prompt: str, user_prompt: str) -> str | None:
    """Deterministic-mode, free-text Groq call (used for phrasing only).
    Returns the text, or None on any failure."""
    client = _get_groq_client()
    if client is None:
        return None
    try:
        completion = client.chat.completions.create(
            model=_GROQ_MODEL,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0,
            timeout=_GROQ_TIMEOUT_SECONDS,
        )
        return completion.choices[0].message.content
    except Exception:
        logger.warning("Groq phrasing call failed; falling back to deterministic template", exc_info=True)
        return None


# ---------------------------------------------------------------------------
# Groq classification — constrained to an exact enum pulled from the
# reference JSON at call time. Any output outside that enum (or the
# explicit 'unclear' escape hatch) is rejected, not used.
# ---------------------------------------------------------------------------


def _groq_classify_single(context: str, message: str, options: dict[str, str]) -> str | None:
    """options is {id: human-readable label}, both taken live from the
    reference JSON. Returns a validated id, or None (unclear / invalid /
    API failure — all treated identically: fall back)."""
    if not options:
        return None
    system_prompt = (
        f"{context} You may ONLY select from the provided list. If nothing matches, "
        "or you are unsure, return 'unclear' — do not guess. Respond with a JSON "
        "object of the exact shape {\"category\": \"<id from the list below, or 'unclear'>\"}. "
        f"Valid options (id: description): {json.dumps(options)}."
    )
    result = _call_groq_json(system_prompt, f"User message: {message}")
    if result is None:
        return None
    category = result.get("category")
    if category == "unclear":
        return None
    if category not in options:
        logger.warning("Groq returned an unrecognized category %r (valid: %r); treating as unclear", category, list(options))
        return None
    return category


def _groq_classify_multiple(context: str, message: str, options: dict[str, str]) -> set[str] | None:
    """Multi-select variant for complications. Returns a validated subset
    of options.keys() (possibly empty — "none apply" is a valid answer),
    or None on failure/invalid output."""
    if not options:
        return set()
    system_prompt = (
        f"{context} Select ALL that apply from the provided list — zero, one, or more "
        "may apply. You may ONLY select ids from the provided list; never invent a new "
        "one. Respond with a JSON object of the exact shape "
        "{\"complications\": [\"<zero or more ids from the list below>\"]}. "
        f"Valid options (id: description): {json.dumps(options)}."
    )
    result = _call_groq_json(system_prompt, f"User message: {message}")
    if result is None:
        return None
    selected = result.get("complications")
    if not isinstance(selected, list):
        logger.warning("Groq complications response was not a list: %r", selected)
        return None
    if any(item not in options for item in selected):
        logger.warning("Groq returned an unrecognized complication in %r (valid: %r); falling back", selected, list(options))
        return None
    return set(selected)


def _resolve_service(message: str, reference: dict[str, Any]) -> str | None:
    options = {sid: s["display_name"] for sid, s in reference["services"].items()}
    result = _groq_classify_single(
        "You are classifying which South African Home Affairs service a user's message is about.",
        message, options,
    )
    if result is not None:
        return result
    logger.info("Falling back to keyword classifier for service classification")
    return _classify_service(message)


def _resolve_sub_case(service_id: str, message: str, reference: dict[str, Any]) -> str | None:
    service = reference["services"][service_id]
    options = {scid: sc["label"] for scid, sc in service["sub_cases"].items()}
    question = _SUB_CASE_QUESTIONS.get(service_id, "")
    result = _groq_classify_single(
        f"You are classifying which sub-case of the '{service['display_name']}' Home Affairs "
        f"service a user's message is about. The user was just asked: {question!r}",
        message, options,
    )
    if result is not None:
        return result
    logger.info("Falling back to keyword classifier for sub_case classification (service=%s)", service_id)
    return _classify_sub_case(service_id, message)


def _resolve_situation(message: str, reference: dict[str, Any]) -> str | None:
    situations = reference["services"]["smart_id"]["sub_cases"]["renewal_or_replacement"]["situations"]
    options = {sid: s["label"] for sid, s in situations.items()}
    result = _groq_classify_single(
        "You are classifying which Smart ID renewal/replacement situation a user's message describes.",
        message, options,
    )
    if result is not None:
        return result
    logger.info("Falling back to keyword classifier for smart_id situation classification")
    return _classify_smart_id_situation(message)


def _resolve_complications(applicable_ids: list[str], message: str, documents_source: dict[str, Any]) -> set[str]:
    conditional = documents_source.get("conditional_documents", {})
    options = {cid: conditional[cid]["trigger_label"] for cid in applicable_ids if cid in conditional}
    result = _groq_classify_multiple(
        "You are identifying which complications, if any, apply to the user's situation.",
        message, options,
    )
    if result is not None:
        return result
    logger.info("Falling back to keyword matcher for complications detection")
    return _detect_complications(applicable_ids, message)


# ---------------------------------------------------------------------------
# Deterministic checklist assembly — reads only the reference JSON, never
# generates a document/fee/fact that isn't there. Unaffected by Groq: this
# section runs identically whether or not Groq is available.
# ---------------------------------------------------------------------------


def _resolve_documents_source(state: ConversationState, sub_case: dict[str, Any]) -> dict[str, Any]:
    """The dict holding 'documents'/'base_documents' + 'conditional_documents'
    for the current state — a situation for smart_id renewals, else the
    sub_case itself."""
    if state.service_id == "smart_id" and state.sub_case_id == "renewal_or_replacement":
        return sub_case["situations"][state.situation_id]
    return sub_case


def _applicable_complication_ids(state: ConversationState, sub_case: dict[str, Any]) -> list[str]:
    src = _resolve_documents_source(state, sub_case)
    return list(src.get("conditional_documents", {}).keys())


def _collect_documents(state: ConversationState, sub_case: dict[str, Any]) -> tuple[list[dict[str, Any]], str | None]:
    src = _resolve_documents_source(state, sub_case)
    documents = list(src.get("documents") or src.get("base_documents") or [])
    conditional = src.get("conditional_documents", {})
    for comp_id in state.complications:
        block = conditional.get(comp_id)
        if block:
            documents.extend(block["documents"])
    return documents, src.get("process_note")


def _format_document_line(item: dict[str, Any]) -> str:
    tail: list[str] = []
    if item.get("issuer"):
        tail.append(f"from {item['issuer']}")

    flags: list[str] = []
    if item.get("original_required") is True:
        flags.append("original required")
    elif item.get("original_required") is False:
        flags.append("original not required")
    if item.get("certified_copy_acceptable") is True:
        flags.append("certified copy acceptable")
    if item.get("personal_attendance_required") is True:
        flags.append("personal attendance required")
    if item.get("biometrics_required") is True:
        flags.append("biometrics required")
    if flags:
        tail.append(", ".join(flags))

    if item.get("applies_when"):
        tail.append(f"applies when {item['applies_when']}")
    if item.get("note"):
        tail.append(item["note"])

    fee = item.get("fee")
    if fee:
        amount = fee.get("amount") or "a fee"
        verify = " (verify before demo — tariffs may change)" if fee.get("verify_before_demo") else ""
        tail.append(f"fee: {amount}{verify}")

    line = item["document"]
    if tail:
        line += " — " + "; ".join(tail)
    return line


