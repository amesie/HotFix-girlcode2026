def _phrasing_implies_false_fee_uncertainty(phrased_text: str, payload: dict[str, Any]) -> bool:
    """Catches the inverse of a hallucinated number: claiming a fee "needs
    confirming" when the source data states it plainly instead
    (verify_before_demo is False, e.g. "Generally free"). Only fires when
    the data is actually certain, so it never flags a genuine
    verify_before_demo=True case."""
    cost = payload.get("cost")
    if not cost or cost.get("verify_before_demo") is not False:
        return False
    text = phrased_text.lower()
    return any(phrase in text for phrase in _FEE_UNCERTAINTY_PHRASES)


def _phrasing_is_grounded(phrased_text: str, payload: dict[str, Any]) -> bool:
    """The automated safety checks on Groq's phrasing: (1) any currency
    figure it states must already appear in the grounding payload, and
    (2) it must not claim a fee "needs confirming" when the data states
    one plainly. Document names/issuers are never at risk of drifting —
    documentsNeeded is always rendered deterministically by
    _format_document_line from the same payload, never by Groq."""
    if not _fee_numbers_in(phrased_text).issubset(_allowed_fee_numbers(payload)):
        return False
    if _phrasing_implies_false_fee_uncertainty(phrased_text, payload):
        return False
    return True


_PHRASING_SYSTEM_PROMPT = (
    "You are writing a warm, conversational reply for a South African Home Affairs "
    "guidance chatbot. Rephrase ONLY the information provided below. Do not add, "
    "infer, or supplement any document, fee, form number, or process detail that is "
    "not explicitly present in this data. If the data says a fee needs confirming "
    "(verify_before_demo is true), say that — do not state a number. If the data "
    "states a cost plainly with nothing to verify (verify_before_demo is false, e.g. "
    "'Generally free'), state it plainly too — do not imply uncertainty and do not "
    "say it needs confirming. Do not mention any service or sub-case other than the "
    "one described below. Keep it to a short paragraph — the itemised document "
    "checklist itself is shown separately, so don't repeat it as a list."
)


def _groq_phrase(payload: dict[str, Any]) -> str | None:
    user_prompt = "Checklist data (the ONLY source of facts you may use):\n" + json.dumps(payload, indent=2)
    return _call_groq_text(_PHRASING_SYSTEM_PROMPT, user_prompt)


def _deterministic_reply_text(
    service: dict[str, Any],
    sub_case: dict[str, Any],
    process_note: str | None,
    general_disclaimer: str,
    cautions: list[str],
) -> str:
    reply_parts = [f"Here's what you'll typically need for {service['display_name']} — {sub_case['label']}:"]
    if process_note:
        reply_parts.append(process_note)
    if sub_case.get("disclaimer"):
        reply_parts.append(sub_case["disclaimer"])
    for exclusion in sub_case.get("important_exclusions", []):
        reply_parts.append(exclusion)
    reply_parts.append(general_disclaimer)
    reply_parts.extend(cautions)
    return " ".join(reply_parts)


def _build_final_reply(
    service: dict[str, Any],
    sub_case: dict[str, Any],
    documents: list[dict[str, Any]],
    cost: dict[str, Any] | None,
    process_note: str | None,
    general_disclaimer: str,
    cautions: list[str],
) -> str:
    payload = _build_grounding_payload(service, sub_case, documents, cost, process_note, general_disclaimer, cautions)
    phrased = _groq_phrase(payload)
    if phrased is not None:
        if _phrasing_is_grounded(phrased, payload):
            return phrased
        logger.warning(
            "Groq phrasing failed the fee-grounding check; falling back to deterministic template. Phrased text: %r",
            phrased,
        )
    return _deterministic_reply_text(service, sub_case, process_note, general_disclaimer, cautions)


