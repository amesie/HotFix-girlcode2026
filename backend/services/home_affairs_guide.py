"""Home Affairs, Explained — conversational guidance chatbot.

Classifies which of 4 Home Affairs services a message is about, asks
branching questions one at a time, and returns a checklist built ONLY from
backend/data/home_affairs_reference.json and backend/data/document_sources.json.
Never invents a document, fee, or fact that isn't in those files.

Matches backend/api/routes.py's binding contract: routes.py looks for one
of get_guidance/handle_chat/chat/answer at import time and binds to
whichever exists, calling it as fn(message, location_dict_or_none,
conversation_id) -> dict shaped {reply, documentsNeeded, estimatedCost,
estimatedTime, nearestBranch, conversationId}. No further routes.py changes
are needed for this module to take over from the existing _chat_stub()
placeholder there (kept in place as the fallback if this module is
unavailable/broken — see routes.py's try/except around _home_affairs_fn()).

GROQ IN THE LOOP — classification and phrasing only, never facts
------------------------------------------------------------------
Groq does exactly two narrow jobs, both constrained and both with a
deterministic fallback if they fail or produce something unvalidated:

  1. CLASSIFICATION (_groq_classify_single / _groq_classify_multiple, used
     by _resolve_service / _resolve_sub_case / _resolve_situation /
     _resolve_complications): temperature 0, JSON-mode structured output,
     given ONLY the exact ids+labels pulled live from
     home_affairs_reference.json as the valid answer set. Any output that
     isn't one of those exact ids (or the explicit 'unclear' escape hatch)
     is rejected and treated as a classification failure — never used.
     On rejection, an API error, or a missing API key, classification
     falls back to the original keyword matchers (_classify_service etc.,
     kept below, unchanged) rather than asking the user again from
     scratch.

  2. PHRASING (_groq_phrase, used by _build_final_reply): takes the exact
     checklist data already assembled from the reference JSON (documents,
     fees, cautions, disclaimers — verbatim) and asks Groq only to
     rephrase it warmly. The prompt explicitly forbids adding any fact not
     in that payload. This is still checked, not just requested: any
     currency figure ("R<number>") in Groq's phrased text must already
     appear in the grounding payload passed to it
     (_phrasing_is_grounded), or the phrasing is discarded and the
     deterministic template is used instead. documentsNeeded itself is
     NEVER passed through Groq — it's always rendered directly from the
     reference JSON by _format_document_line, regardless of whether
     phrasing succeeds.

Neither call ever runs without its constraining system prompt and
reference-derived data attached — there is no "general knowledge" mode.

CONVERSATION STATE
-------------------
Sessions are keyed by conversationId (backend/api/routes.py's ChatRequest
field, generated by the frontend once per chat and sent on every turn — see
frontend/src/screens/ChatbotScreen.tsx). Two different conversationIds are
completely isolated from each other. A missing conversationId degrades
safely to a fresh, single-turn-only session (a random key per call) rather
than falling back to a shared key, so concurrent callers can never collide.
"""

