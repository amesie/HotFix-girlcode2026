# ---------------------------------------------------------------------------
# Groq client + low-level call seams. Tests monkeypatch _call_groq_json and
# _call_groq_text directly rather than mocking the SDK client, mirroring
# how tests/test_api.py monkeypatches routes._detection_fn.
