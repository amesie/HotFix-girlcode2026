def answer(message: str, location: dict[str, Any] | None = None, conversation_id: str | None = None) -> dict[str, Any]:
    """Classify + advance the conversation one step, returning a response
    shaped {reply, documentsNeeded, estimatedCost, estimatedTime,
    nearestBranch, conversationId}.
    """
    resolved_conversation_id = conversation_id or str(uuid.uuid4())
    key = _session_key(conversation_id)
    state = _SESSIONS.get(key) or ConversationState()

    reference = load_reference()

    def respond(resp: dict[str, Any]) -> dict[str, Any]:
        resp["conversationId"] = resolved_conversation_id
        return resp

    if state.stage == "service":
        service_id = _resolve_service(message, reference)
        if service_id is None:
            _SESSIONS[key] = state
            return respond(_clarify_service_response())
        state.service_id = service_id
        state.stage = "sub_case"

    service = reference["services"][state.service_id]

    if state.stage == "sub_case":
        sub_case_id = _resolve_sub_case(state.service_id, message, reference)
        if sub_case_id is None:
            _SESSIONS[key] = state
            return respond(_clarify_sub_case_response(state.service_id))
        state.sub_case_id = sub_case_id
        sub_case = service["sub_cases"][sub_case_id]
        if sub_case.get("not_covered"):
            _SESSIONS.pop(key, None)
            return respond(_not_covered_response(sub_case))
        state.stage = "situation" if (state.service_id == "smart_id" and sub_case_id == "renewal_or_replacement") else "complications"

    sub_case = service["sub_cases"][state.sub_case_id]

    if state.stage == "situation":
        situation_id = _resolve_situation(message, reference)
        if situation_id is None:
            _SESSIONS[key] = state
            return respond(_clarify_situation_response())
        state.situation_id = situation_id
        state.stage = "complications"

    applicable = _applicable_complication_ids(state, sub_case)

    if state.stage == "complications":
        if not applicable:
            state.stage = "done"
        else:
            state.stage = "awaiting_complications_answer"
            _SESSIONS[key] = state
            return respond(_clarify_complications_response(applicable, state, sub_case))

    if state.stage == "awaiting_complications_answer":
        documents_source = _resolve_documents_source(state, sub_case)
        state.complications |= _resolve_complications(applicable, message, documents_source)
        state.stage = "done"

    _SESSIONS.pop(key, None)
    return respond(_final_response(state, reference, service, sub_case))
