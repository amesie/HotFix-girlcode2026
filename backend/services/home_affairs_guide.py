def _trailing_source_cautions(documents: list[dict[str, Any]]) -> list[str]:
    seen: set[str] = set()
    notes: list[str] = []
    for doc in documents:
        for ref in doc.get("source_refs", []):
            if ref in _SOURCE_REF_CAUTIONS and ref not in seen:
                seen.add(ref)
                notes.append(_SOURCE_REF_CAUTIONS[ref])
    return notes


def _format_cost(cost: dict[str, Any] | None) -> str:
    if cost is None:
        return "Not specified in our reference material — confirm the current fee with Home Affairs."
    amount = cost.get("amount") or "A fee applies"
    verify = " (verify before demo — tariffs may change)" if cost.get("verify_before_demo") else ""
    note = f" — {cost['note']}" if cost.get("note") else ""
    return f"{amount}{verify}{note}"


