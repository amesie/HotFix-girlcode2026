@dataclass
class ConversationState:
    service_id: str | None = None
    sub_case_id: str | None = None
    situation_id: str | None = None  # only used for smart_id renewal_or_replacement
    complications: set[str] = field(default_factory=set)
    stage: str = "service"  # service -> sub_case -> situation? -> complications -> awaiting_complications_answer -> done


_SESSIONS: dict[str, ConversationState] = {}


def _session_key(conversation_id: str | None) -> str:
    if conversation_id:
        return f"conv:{conversation_id}"
    # No id supplied: degrade to an isolated one-off session (never a
    # shared key) so concurrent callers without an id can't collide.
    return f"conv:anonymous:{uuid.uuid4()}"


def reset_sessions() -> None:
    """Clear all in-memory conversation state. Used by tests between cases."""
    _SESSIONS.clear()


